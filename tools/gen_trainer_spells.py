#!/usr/bin/env python3
"""Generate Data/TrainerSpells.lua from the CMaNGOS classic-db dump.

Trainer rows (npc_trainer, npc_trainer_template) list the *teaching* spell; spell_template
maps it (effect 36 LEARN_SPELL) to the recipe spell. Output:
  ns.TrainerSpells[recipeSpellID] = "skill/cost"   (lowest required skill and cost over all trainers)
Usage: gen_trainer_spells.py <ClassicDB.sql.gz> <out.lua>
"""
import gzip, re, sys

PROF = {171, 164, 333, 202, 165, 197, 185, 129, 186, 356, 182}

def rows(sql, table):
    for line in sql:
        if line.startswith("INSERT INTO `%s` VALUES" % table):
            body = line.split("VALUES", 1)[1]
            yield from split_rows(body)

def split_rows(body):
    i, n = 0, len(body)
    while i < n:
        if body[i] != "(":
            i += 1
            continue
        vals, cur, i, q = [], "", i + 1, False
        while i < n:
            ch = body[i]
            if q:
                if ch == "\\":
                    cur += body[i:i + 2]; i += 2; continue
                if ch == "'":
                    q = False
                cur += ch
            elif ch == "'":
                q = True; cur += ch
            elif ch == ",":
                vals.append(cur); cur = ""
            elif ch == ")":
                vals.append(cur); i += 1; break
            else:
                cur += ch
            i += 1
        yield vals

def main(src, out):
    lines = gzip.open(src, "rt", encoding="utf-8", errors="replace").read().split("\n")
    teach = {}
    for v in rows(lines, "spell_template"):
        sid = int(v[0])
        for k in range(3):
            if v[61 + k] == "36" and int(v[109 + k]) > 0:
                teach[sid] = int(v[109 + k])
    best = {}
    for table in ("npc_trainer", "npc_trainer_template"):
        for v in rows(lines, table):
            spell, cost, reqskill, val = int(v[1]), int(v[2]), int(v[3]), int(v[4])
            if reqskill not in PROF:
                continue
            rid = teach.get(spell, spell)
            b = best.get(rid)
            if not b or val < b[0] or (val == b[0] and cost < b[1]):
                best[rid] = (val, cost)
    with open(out, "w", encoding="utf-8") as f:
        f.write("-- RecipeManager - profession recipes taught by trainers (recipe spell -> \"required skill/cost in copper\").\n")
        f.write("-- Generated by tools/gen_trainer_spells.py from CMaNGOS classic-db (GPL-2.0). Do not edit.\n")
        f.write("local _, ns = ...\nns.TrainerSpells = {\n")
        for rid in sorted(best):
            f.write('[%d]="%d/%d",\n' % (rid, *best[rid]))
        f.write("}\n")
    print(len(best), "trainer recipes,", len(teach), "teach spells")

if __name__ == "__main__":
    main(*sys.argv[1:3])
