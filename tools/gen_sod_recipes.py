#!/usr/bin/env python3
"""Generate Data/SoDRecipes.lua: Season-of-Discovery profession recipes (spell IDs).

Source: AtlasLootClassic_Crafting (GPL-2.0): every recipe spell listed in data-sod.lua that is
neither in data.lua (Classic) nor in data-tbc.lua. SoD spells below 400000 are ignored (old
Classic spells that only the SoD list still carries).
Usage: gen_sod_recipes.py <data.lua> <data-tbc.lua> <data-sod.lua> <out.lua>
"""
import re, sys

def ids(path):
    s = open(path, encoding="utf-8", errors="replace").read()
    out = {}
    blocks = re.split(r'\ndata\["([A-Za-z0-9_]+)"\]\s*=\s*\{', s)
    for i in range(1, len(blocks), 2):
        for x in re.findall(r'\{\s*\d+\s*,\s*(\d{3,8})\s*\}', blocks[i + 1]):
            out[int(x)] = blocks[i]
    return out

def main(classic, tbc, sod, out):
    a, b, c = ids(classic), ids(tbc), ids(sod)
    res = sorted(k for k in c if k not in a and k not in b and k >= 400000)
    with open(out, "w", encoding="utf-8") as f:
        f.write("-- RecipeManager - Season of Discovery recipe spells (not part of WoW Forever), hidden everywhere.\n")
        f.write("-- Generated by tools/gen_sod_recipes.py from AtlasLootClassic_Crafting (GPL-2.0). Do not edit.\n")
        f.write("local _, ns = ...\nns.SoDRecipes = {\n")
        for i in range(0, len(res), 10):
            f.write(" ".join("[%d]=true," % k for k in res[i:i + 10]) + "\n")
        f.write("}\n")
    print(len(res), "SoD recipe spells")

if __name__ == "__main__":
    main(*sys.argv[1:5])
