#!/usr/bin/env python3
"""Generate Data/SeasonalVendors.lua from the CMaNGOS classic-db dump.

A recipe vendor counts as seasonal when every spawn of it belongs to a game event
(game_event_creature with a positive event). Output: ns.SeasonalVendors[npcID] = holidayID
(client-side holiday id of that event, e.g. 141 = Feast of Winter Veil).
Usage: gen_seasonal_vendors.py <ClassicDB.sql.gz> <out.lua>
"""
import collections, gzip, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_trainer_spells import rows

def main(src, out):
    lines = gzip.open(src, "rt", encoding="utf-8", errors="replace").read().split("\n")
    holiday = {int(v[0]): int(v[4]) for v in rows(lines, "game_event")}
    event_of = {int(v[0]): int(v[1]) for v in rows(lines, "game_event_creature")}
    recipe = {int(v[0]) for v in rows(lines, "item_template") if v[1] == "9"}
    names = {int(v[0]): v[1].strip("'") for v in rows(lines, "creature_template")}
    vendors = {int(v[0]) for v in rows(lines, "npc_vendor") if int(v[1]) in recipe}
    spawns = collections.defaultdict(list)
    for v in rows(lines, "creature"):
        spawns[int(v[1])].append(event_of.get(int(v[0]), 0))
    res = {}
    for npc in sorted(vendors):
        ev = spawns.get(npc)
        if ev and all(e > 0 for e in ev):
            h = {holiday.get(e, 0) for e in ev}
            if len(h) == 1 and 0 not in h:
                res[npc] = h.pop()
    with open(out, "w", encoding="utf-8") as f:
        f.write("-- RecipeManager - recipe vendors that are only there during a world event (npc -> client holiday id).\n")
        f.write("-- Generated by tools/gen_seasonal_vendors.py from CMaNGOS classic-db (GPL-2.0). Do not edit.\n")
        f.write("local _, ns = ...\nns.SeasonalVendors = {\n")
        for npc, h in res.items():
            f.write("[%d]=%d, -- %s\n" % (npc, h, names.get(npc, "?")))
        f.write("}\n")
    print(len(res), "seasonal recipe vendors")

if __name__ == "__main__":
    main(*sys.argv[1:3])
